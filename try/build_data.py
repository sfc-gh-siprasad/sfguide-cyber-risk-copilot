"""Build try/data.js for the hosted no-install example.

Uses the same analytics and sample answers as the Streamlit app, so the hosted
example shows identical numbers.

    python try/build_data.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))

import analytics  # noqa: E402
import mock_backend  # noqa: E402


def records(df):
    out = df.copy()
    for c in out.columns:
        if str(out[c].dtype).startswith("datetime"):
            out[c] = out[c].dt.strftime("%Y-%m-%d")
        elif str(out[c].dtype) == "category":
            out[c] = out[c].astype(str)
    return json.loads(out.to_json(orient="records"))


def main():
    frames = mock_backend.load_frames()
    df = analytics.prepare(frames)

    services = analytics.by_service(df)
    priority = {name: records(analytics.priority_queue(df[df["service_name"] == name], limit=15))
                for name in services["service_name"]}
    trend = analytics.monthly_trend(df)
    trend["month"] = trend["month"].dt.strftime("%b %Y")

    answers = {}
    for q in mock_backend.SAMPLE_QUESTIONS:
        r = mock_backend.ask(q, df, frames)
        answers[q] = {"answer": r["answer"], "sources": r["sources"],
                      "table": records(r["table"]) if r["table"] is not None else None}

    data = {
        "asOf": "1 November 2026",
        "kpis": analytics.kpis(df),
        "severity": records(analytics.by_severity(df)),
        "trend": records(trend),
        "aging": records(analytics.aging_buckets(df)),
        "services": records(services),
        "priority": priority,
        "questions": mock_backend.SAMPLE_QUESTIONS,
        "answers": answers,
        "policies": records(frames["policies"]),
    }
    out = ROOT / "try" / "data.js"
    out.write_text("// Generated by try/build_data.py from synthetic data. Do not edit.\nwindow.CYBER_DATA = "
                   + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
