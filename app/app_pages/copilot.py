import streamlit as st

import common

ctx = common.context()
backend, df, frames = ctx["backend"], ctx["df"], ctx["frames"]

st.title("Ask the copilot")
if ctx["live"]:
    st.badge("Powered by Cortex Agents, Cortex Analyst and Cortex Search", icon=":material/bolt:", color="blue")
else:
    st.badge("Sample AI response mode: answers are templated from the bundled data, not live model output",
             icon=":material/info:", color="orange")

if "messages" not in st.session_state:
    st.session_state.messages = []


def render(msg):
    st.markdown(msg["content"])
    if msg.get("mocked"):
        st.badge("Sample AI response", color="orange")
    if msg.get("table") is not None and len(msg["table"]):
        st.dataframe(msg["table"], hide_index=True, alt="Result table for the answer above")
    if msg.get("sources"):
        with st.expander("Policy sources", icon=":material/menu_book:", expanded=True):
            for s in msg["sources"]:
                st.markdown(f"**{s['title']}**")
                st.caption(s["text"])
    if msg.get("sql"):
        with st.expander("SQL generated by Cortex Analyst", icon=":material/code:"):
            st.code(msg["sql"], language="sql")


def pick(q):
    st.session_state.pending = q


for m in st.session_state.messages:
    with st.chat_message(m["role"]):
        render(m)

suggestions = st.empty()
if not st.session_state.messages:
    with suggestions.container():
        st.caption("Try one of these:")
        with st.container(horizontal=True):
            for q in backend.SAMPLE_QUESTIONS:
                st.button(q, on_click=pick, args=(q,), key=f"q_{q}", icon=":material/arrow_forward:")

prompt = st.chat_input("Ask about posture, exposure, ownership, or policy") or st.session_state.pop("pending", None)
if prompt:
    suggestions.empty()
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)
    with st.chat_message("assistant"):
        with st.spinner("Thinking"):
            try:
                r = backend.ask(prompt, df, frames)
                msg = {"role": "assistant", "content": r["answer"], "table": r["table"], "sources": r["sources"],
                       "sql": r["sql"], "mocked": r["mocked"]}
            except Exception as exc:
                msg = {"role": "assistant", "content": f"The agent call failed: {exc}", "mocked": False}
        render(msg)
    st.session_state.messages.append(msg)
