"""No-account mode: bundled synthetic data and clearly labelled sample answers.

Numbers in every answer are computed from the bundled CSVs. The wording is
templated, not generated by a model, and the app labels it "Sample AI response".
"""

import re
from pathlib import Path

import pandas as pd

import analytics

DATA = Path(__file__).resolve().parents[1] / "data"
MODE_LABEL = "Sample data (no Snowflake account)"

SAMPLE_QUESTIONS = [
    "Which Tier 1 services have the most open critical findings?",
    "What is our SLA breach rate for internet-facing assets?",
    "Which teams have the most overdue findings?",
    "How many open findings are older than 90 days?",
    "What does policy say about remediation deadlines for known exploited findings?",
    "Which production assets have no owner?",
]


def load_frames() -> dict:
    return {n: pd.read_csv(DATA / f"{n}.csv") for n in ("findings", "assets", "services", "teams", "policies")}


def _policy_hits(question: str, policies: pd.DataFrame, k: int = 2) -> list:
    words = {w for w in re.findall(r"[a-z]{4,}", question.lower())} - {"what", "does", "say", "about", "which", "have", "with"}
    scored = []
    for _, p in policies.iterrows():
        text = f"{p['title']} {p['category']} {p['content']}".lower()
        score = sum(text.count(w) for w in words) + 3 * sum(w in p["title"].lower() for w in words)
        if score:
            scored.append((score, p))
    scored.sort(key=lambda x: -x[0])
    return [{"title": p["title"], "text": p["content"]} for _, p in scored[:k]]


def _ans(text, table=None, sources=None, chart=None):
    return {"answer": text, "table": table, "sources": sources or [], "sql": None, "chart": chart, "mocked": True}


def ask(question: str, df: pd.DataFrame, frames: dict) -> dict:
    q = question.lower()
    open_df = df[df["is_open"]]

    if "tier 1" in q and "critical" in q:
        t = open_df[open_df["tier"] == 1].groupby("service_name").agg(
            open_critical=("is_open_critical", "sum"), open_findings=("finding_id", "count")).reset_index()
        t["open_critical"] = t["open_critical"].astype(int)
        t = t.sort_values(["open_critical", "open_findings"], ascending=False).head(5).reset_index(drop=True)
        top = t.iloc[0]
        return _ans(f"**{top['service_name']}** has the most open critical findings among Tier 1 services "
                    f"({top['open_critical']}). The top five are below.", t)

    if "sla" in q and ("internet" in q or "exposed" in q or "external" in q):
        t = open_df.groupby("internet_facing").agg(
            open_findings=("finding_id", "count"), overdue=("is_overdue", "sum")).reset_index()
        t["sla_breach_rate"] = (t["overdue"] / t["open_findings"]).round(3)
        t["internet_facing"] = t["internet_facing"].map({True: "Internet-facing", False: "Internal"})
        t["overdue"] = t["overdue"].astype(int)
        ext = t[t["internet_facing"] == "Internet-facing"].iloc[0]
        return _ans(f"The SLA breach rate for internet-facing assets is **{ext['sla_breach_rate']:.1%}** "
                    f"({ext['overdue']} of {ext['open_findings']} open findings are overdue).", t,
                    _policy_hits("remediation deadline internet-facing exposure", frames["policies"], 1))

    if "team" in q and ("overdue" in q or "breach" in q or "most" in q):
        t = analytics.by_team(df).head(5)
        t["overdue"] = t["overdue"].astype(int)
        t["open_critical"] = t["open_critical"].astype(int)
        top = t.iloc[0]
        return _ans(f"**{top['team_name']}** has the most overdue findings ({top['overdue']}). Top five teams are below.", t)

    if "older than" in q or "aging" in q or "aged" in q or "90 days" in q:
        n = int((open_df["open_age_days"] > 90).sum())
        crit = int(((open_df["open_age_days"] > 90) & (open_df["severity"] == "Critical")).sum())
        t = analytics.aging_buckets(df).groupby("bucket", observed=False)["Open findings"].sum().reset_index()
        return _ans(f"**{n}** open findings are older than 90 days, including **{crit}** Critical.", t,
                    _policy_hits("monthly posture review aging", frames["policies"], 1))

    if "no owner" in q or "unowned" in q or "without owner" in q:
        a = frames["assets"]
        t = a[a["owner_team_id"].isna() & (a["environment"] == "Production")][
            ["asset_name", "asset_type", "service_id", "criticality"]].reset_index(drop=True)
        return _ans(f"**{len(t)}** production assets have no owning team in the inventory.", t.head(10),
                    _policy_hits("asset ownership standard", frames["policies"], 1))

    hits = _policy_hits(question, frames["policies"])
    if hits:
        return _ans("Here is what the bundled policy documents say that is most relevant to your question.", None, hits)
    return _ans("This sample mode answers the suggested questions. Connect to Snowflake for open-ended questions "
                "answered by a Cortex Agent.")
